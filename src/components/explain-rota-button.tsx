"use client";

import React from "react";
import { Loader2, Sparkles } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Dialog, DialogContent, DialogDescription, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { useToast } from "@/hooks/use-toast";

type Explanation = { summary: string; perMember: { member: string; reason: string }[]; risks: string[] };

/** Asks Gemini (via /api/ai/explain-rota) why each person got their shift. */
export function ExplainRotaButton({ generationId }: { generationId: string }) {
  const { toast } = useToast();
  const [open, setOpen] = React.useState(false);
  const [loading, setLoading] = React.useState(false);
  const [result, setResult] = React.useState<Explanation | null>(null);

  const explain = async (e: React.MouseEvent) => {
    e.stopPropagation();
    setLoading(true);
    try {
      const res = await fetch("/api/ai/explain-rota", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ generationId }),
      });
      const data = await res.json().catch(() => ({}));
      if (!res.ok) throw new Error(data.error || "The explanation could not be generated.");
      setResult(data);
      setOpen(true);
    } catch (err) {
      toast({ variant: "destructive", title: "No explanation", description: err instanceof Error ? err.message : "Try again." });
    } finally {
      setLoading(false);
    }
  };

  return (
    <>
      <Button variant="ghost" size="icon" className="shrink-0" onClick={explain} disabled={loading} aria-label="Explain this rota">
        {loading ? <Loader2 className="h-4 w-4 animate-spin" /> : <Sparkles className="h-4 w-4" />}
      </Button>
      <Dialog open={open} onOpenChange={setOpen}>
        <DialogContent className="sm:max-w-xl max-h-[85vh] overflow-y-auto" onClick={e => e.stopPropagation()}>
          <DialogHeader>
            <DialogTitle>Why this rota looks the way it does</DialogTitle>
            <DialogDescription>Generated by Gemini from the rota rules and assignments. Check it before sharing.</DialogDescription>
          </DialogHeader>
          {result && (
            <div className="space-y-4 text-sm">
              <p>{result.summary}</p>
              <ul className="space-y-2">
                {result.perMember.map(m => (
                  <li key={m.member}><span className="font-medium">{m.member}:</span> <span className="text-muted-foreground">{m.reason}</span></li>
                ))}
              </ul>
              {result.risks.length > 0 && (
                <div className="rounded-lg border border-amber-500/30 bg-amber-500/10 p-3">
                  <div className="font-medium mb-1">Things to check</div>
                  <ul className="list-disc pl-5 space-y-1">{result.risks.map(r => <li key={r}>{r}</li>)}</ul>
                </div>
              )}
            </div>
          )}
        </DialogContent>
      </Dialog>
    </>
  );
}
